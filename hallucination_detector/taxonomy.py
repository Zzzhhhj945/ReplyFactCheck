# 严重度 rubric：影响维度 × 偏离程度 → 严重度
# 影响维度：健康安全 > 交易资金/服务承诺 > 产品认知 > 营销体验
# 偏离程度：完全杜撰 > 偏差 > 遗漏
SEVERITY_RUBRIC = {
    ("健康安全", "完全杜撰"): "高",
    ("交易资金", "完全杜撰"): "高",
    ("服务承诺", "完全杜撰"): "高",
    ("产品认知", "完全杜撰"): "高",
    ("营销体验", "完全杜撰"): "中",
    ("交易资金", "偏差"): "中",
    ("服务承诺", "偏差"): "中",
    ("产品认知", "偏差"): "中",
    ("产品认知", "遗漏"): "低",
    ("营销体验", "遗漏"): "低",
}

IMPACTS = ("健康安全", "交易资金", "服务承诺", "产品认知", "营销体验")
DEGREES = ("完全杜撰", "偏差", "遗漏")


def severity_from_rubric(impact, degree):
    """按 rubric 计算严重度，未覆盖的组合默认「中」。"""
    return SEVERITY_RUBRIC.get((impact, degree), "中")


def category_of(hallucination_type):
    """细类 -> 主类；无幻觉返回自身。"""
    if hallucination_type == NO_HALLUCINATION:
        return NO_HALLUCINATION
    return FINE_TYPES[hallucination_type][0]


ALL_TYPES = tuple(FINE_TYPES.keys()) + (NO_HALLUCINATION,)
